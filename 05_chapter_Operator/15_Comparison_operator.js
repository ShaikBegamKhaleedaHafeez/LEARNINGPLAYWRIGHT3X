//= -> assignment operator
// == -> comparison operator (checks for value equality)
// === -> strict equality operator (checks for both value and type equality)
console.log(5 == "5"); // Output: true (value is equal, type is not checked)
console.log(5 === "5"); // Output: false (value is equal but type is not checked)

//>,<,>=,<= -> comparison operators
console.log(10 > 5); // Output: true
console.log(10 < 5); // Output: false
console.log(10 >= 10); // Output: true
console.log(10 <= 10); // Output: true

//!= -> not equal operator
console.log(10 != 5); // Output: true (10 is not equal to 5)
//!== -> strict not equal operator
console.log(10 !== "10"); // Output: true (10 is not equal to "10" in type) 